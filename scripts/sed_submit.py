#!/usr/bin/env python3
"""Create Slurm ``bin-fit`` jobs for TS-filtered SED-bin XML models."""

from __future__ import annotations

import argparse
import shlex
import stat
from pathlib import Path

from sed_filter import load_config, output_model_path


SUBMIT_DELAY_SECONDS = 3


def write_sbatch(job, settings):
    """Write one ``bin-fit`` Slurm script without submitting it."""
    tag = f"sed-{settings['nbins']}bin-tslt{settings['threshold']:g}-{job['ibin']:02d}"
    sbatch_file = settings["sbatch_dir"] / f"{tag}.sbatch"
    node = settings["nodes"][(job["ibin"] - 1) % len(settings["nodes"])]

    content = f"""#!/usr/bin/env bash
# Generated by fermiflow sed-submit. Review before submission.
#SBATCH --job-name={tag}
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --cpus-per-task=1
#SBATCH --nodelist={node}
#SBATCH --output={settings['log_dir']}/%x-%j.log
#SBATCH --error={settings['log_dir']}/%x-%j.log

set -eo pipefail
source {shlex.quote(str(settings['conda_sh']))}
conda activate {shlex.quote(settings['conda_env'])}

echo "Job ID:      ${{SLURM_JOB_ID}}"
echo "Node:        $(hostname)"
echo "SED bin:     {job['ibin']}/{settings['nbins']}"
echo "Input model: {job['output_model']}"

cd {shlex.quote(str(settings['working_dir']))}
exec fermiflow run --config {shlex.quote(str(settings['project_config']))} \\
    --mode bin-fit --nbins {settings['nbins']} --ibin {job['ibin']} \\
    --input-model {shlex.quote(str(job['output_model']))}
"""
    sbatch_file.write_text(content, encoding="utf-8")
    sbatch_file.chmod(sbatch_file.stat().st_mode | stat.S_IXUSR)
    return sbatch_file


def write_submit_script(sbatch_files, sbatch_dir):
    """Write a master submission script with a fixed gap between jobs."""
    submit_script = sbatch_dir / "submit_sed_filter.sh"
    commands = f"\nsleep {SUBMIT_DELAY_SECONDS}\n".join(
        f"sbatch {shlex.quote(str(sbatch_file))}" for sbatch_file in sbatch_files
    )
    submit_script.write_text(
        "#!/usr/bin/env bash\n"
        "set -euo pipefail\n\n"
        "# Review the .sbatch files before running this script.\n"
        f"{commands}\n",
        encoding="utf-8",
    )
    submit_script.chmod(submit_script.stat().st_mode | stat.S_IXUSR)
    return submit_script


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, required=True)
    args = parser.parse_args()
    settings = load_config(args.config)

    if not settings["project_config"].is_file():
        raise FileNotFoundError(f"Project configuration not found: {settings['project_config']}")
    if not settings["nodes"]:
        raise ValueError("slurm.nodes must contain at least one node.")

    jobs = []
    missing_models = []
    for configured_job in settings["jobs"]:
        output_model = configured_job.get("output_model") or output_model_path(
            configured_job["input_model"], settings["threshold"]
        )
        job = {"ibin": configured_job["ibin"], "output_model": output_model}
        if output_model.is_file():
            jobs.append(job)
        else:
            missing_models.append((configured_job["ibin"], output_model))

    if missing_models:
        details = "\n".join(f"  bin {ibin}: {path}" for ibin, path in missing_models)
        raise FileNotFoundError(
            "Run `fermiflow sed-filter` first; filtered XML model(s) are missing:\n"
            + details
        )

    settings["sbatch_dir"].mkdir(parents=True, exist_ok=True)
    settings["log_dir"].mkdir(parents=True, exist_ok=True)
    sbatch_files = [write_sbatch(job, settings) for job in jobs]
    submit_script = write_submit_script(sbatch_files, settings["sbatch_dir"])

    print("Created Slurm files:")
    for sbatch_file in sbatch_files:
        print(f"  {sbatch_file}")
    print(f"Submit script: {submit_script}")
    print("Review it, then run:")
    print(f"  bash {submit_script}")


if __name__ == "__main__":
    main()
